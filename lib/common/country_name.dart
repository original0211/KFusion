import 'package:material_ui/material_ui.dart';

/// The bundled country table is deliberately partial: it covers the
/// codes an exit address plausibly reports, in every language the app
/// ships. A code outside the table resolves to null so callers can drop
/// the country segment instead of showing a raw code.
String? countryName(String code, Locale locale) {
  final names = _countryNames[code.toUpperCase()];
  if (names == null) {
    return null;
  }
  final index = switch (locale.languageCode) {
    'es' => 1,
    'fr' => 2,
    'ja' => 3,
    'ko' => 4,
    'ru' => 5,
    'zh' => 6,
    _ => 0,
  };
  return names[index];
}

